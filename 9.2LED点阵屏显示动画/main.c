#include <REGX52.H>
#include "Delay.h"
#include "MatrixLED.h"

unsigned char Animation[]={
	0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
	0x7F,0x08,0x08,0x08,0x7F,0x00,0x0E,0x15,
	0x15,0x0C,0x00,0x7F,0x01,0x00,0x7F,0x01,
	0x00,0x06,0x09,0x09,0x06,0x00,0x7D,0x00,
	0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00
};
void main()
{
	unsigned char i,Offset=3,Count=0;
	MatrixLED_Init();
	
	while(1)
	{	
		for(i=0;i<8;i++)
		{
			MatrixLED_ShowColumn(i,Animation[i+Offset]);
		}
		Count++;
		if(Count>10)
		{
			Count=0;
			Offset++;
			if(Offset>32)//防止数组溢出（32+8总长度）
			{
				Offset=0;
			}
		}
	}
}
